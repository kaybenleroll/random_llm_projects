# ----------------------------------------------------------------------------- data
def load_data():
    """Returns per-judge arrays and per-arm run costs."""
    data = {j: {"arm": [], "run": [], "item": [], "y": []} for j in JUDGES}
    run_ids = {}      # (arm, n) -> global run index
    costs = {a: {} for a in ARM_NAMES}
    for arm, (jd, rd, *_rest) in ARMS.items():
        for f in sorted(glob.glob(os.path.join(HERE, jd, arm, "*.json"))):
            m = re.match(r"(\d+)\.(j-[a-z\-]+)\.json$", os.path.basename(f))
            n, judge = int(m.group(1)), m.group(2)
            d = json.load(open(f))
            assert d["ok"], f
            key = (arm, n)
            rid = run_ids.setdefault(key, len(run_ids))
            for it in range(1, N_ITEMS + 1):
                data[judge]["arm"].append(ARM_NAMES.index(arm))
                data[judge]["run"].append(rid)
                data[judge]["item"].append(it - 1)
                data[judge]["y"].append(int(bool(d["found"][str(it)]["found"])))
            assert d["recall_count"] == sum(data[judge]["y"][-N_ITEMS:]), f
        for (a2, n) in [k for k in run_ids if k[0] == arm]:
            rf = os.path.join(HERE, rd, arm, f"{n}.json")
            if not os.path.exists(rf):        # sonnet-max: only .failed.json/.recovered.json exist
                rf = os.path.join(HERE, rd, arm, f"{n}.failed.json")
            c = json.load(open(rf))["cost_usd"]
            assert c is not None, rf
            costs[arm][n] = float(c)
    for j in JUDGES:
        for k in data[j]:
            data[j][k] = np.asarray(data[j][k], dtype=int)
    return data, run_ids, {a: np.array([v for _, v in sorted(costs[a].items())]) for a in ARM_NAMES}


# ----------------------------------------------------------------------------- fitting
def design(kind):
    """arm list + T matrix mapping free arm parameters to arm effects."""
    arms = FABLE_ARMS if kind == "fable" else ARM_NAMES
    if kind == "m2":
        free = [a for a in arms if a != "sonnet-5-max-cap10"]
        T = np.zeros((len(arms), len(free) + 1))
        for i, a in enumerate(arms):
            if a == "sonnet-5-max-cap10":
                T[i, free.index("sonnet-max")] = 1.0
                T[i, -1] = 1.0       # delta
            else:
                T[i, free.index(a)] = 1.0
        return arms, T
    return arms, np.eye(len(arms))


def fit(kind, judge, data, refit=False):
    path = os.path.join(CACHE, f"{kind}_{judge}.npz")
    if os.path.exists(path) and not refit:
        z = np.load(path, allow_pickle=True)
        return {k: z[k] for k in z.files}
    os.makedirs(CACHE, exist_ok=True)
    arms, T = design(kind)
    D = data[judge]
    keep = np.isin(D["arm"], [ARM_NAMES.index(a) for a in arms])
    arm_full = D["arm"][keep]
    arm_idx = np.array([arms.index(ARM_NAMES[i]) for i in arm_full])
    run_raw = D["run"][keep]
    _, run_idx = np.unique(run_raw, return_inverse=True)
    item_idx, y = D["item"][keep], D["y"][keep]
    n_run, n_arm, P = int(run_idx.max() + 1), len(arms), int(T.shape[1])
    inter = kind == "m1x"
    with pm.Model():
        mu = pm.Normal("mu", 0, 2)
        th = pm.Normal("theta", 0, 1.5, shape=P)
        if kind == "m2":
            # last parameter is delta (cap10 prompt effect), tighter prior
            th = pm.Deterministic("theta_all", pm.math.concatenate([th[:-1], (th[-1:] * (1.0 / 1.5))]))
        A = pm.Deterministic("A", pm.math.dot(T, th))
        s_b = pm.HalfNormal("sigma_b", 2.5)
        z = pm.Normal("z", 0, 1, shape=N_ITEMS)
        b = pm.Deterministic("b", s_b * z)
        s_c = pm.HalfNormal("sigma_c", 1.5)
        u = pm.Normal("u", 0, 1, shape=n_run)
        eta = mu + A[arm_idx] + b[item_idx] + s_c * u[run_idx]
        if inter:
            s_d = pm.HalfNormal("sigma_d", 1.0)
            w = pm.Normal("w", 0, 1, shape=(n_arm, N_ITEMS))
            pm.Deterministic("d", s_d * w)
            eta = eta + s_d * w[arm_idx, item_idx]
        pm.Bernoulli("y", logit_p=eta, observed=y)
        tr = pm.sample(1000, tune=1500, chains=4, cores=4, target_accept=0.92,
                       random_seed=SEED + hash_str(kind + judge), progressbar=False,
                       idata_kwargs={"log_likelihood": False})
    post = tr.posterior
    out = {"mu": post["mu"].values, "A": post["A"].values, "b": post["b"].values,
           "sigma_c": post["sigma_c"].values, "sigma_b": post["sigma_b"].values,
           "arms": np.array(arms),
           "divergences": np.array(int(tr.sample_stats["diverging"].values.sum()))}
    if inter:
        out["d"] = post["d"].values
        out["sigma_d"] = post["sigma_d"].values
    if kind == "m2":
        out["delta"] = post["theta_all"].values[..., -1]
    # sampler diagnostics on raw parameters
    diag = {}
    for name in ["mu", "A", "b", "sigma_b", "sigma_c"] + (["sigma_d"] if inter else []) + (["delta"] if kind == "m2" else []):
        arr = out[name]
        arr = arr.reshape(arr.shape[0], arr.shape[1], -1)
        diag[name] = (float(np.nanmax(az.rhat(arr))), float(np.nanmin(az.ess(arr))))
    out["diag"] = np.array(json.dumps(diag))
    np.savez(path, **out)
    return {k: out[k] for k in out}


def hash_str(s):
    return sum(ord(c) * (i + 1) for i, c in enumerate(s)) % 10000


# ----------------------------------------------------------------------------- posterior functionals
GH_X, GH_W = np.polynomial.hermite_e.hermegauss(40)
GH_W = GH_W / np.sqrt(2 * np.pi)


def expit(x):
    return 1 / (1 + np.exp(-x))


def eta_arm(F, ai):
    """(chain, draw, item) linear predictor without run intercept for arm index ai."""
    e = F["mu"][..., None] + F["A"][..., ai, None] + F["b"]
    if "d" in F:
        e = e + F["d"][..., ai, :]
    return e


def arm_mean(F, ai):
    """Expected recall count of the arm mean (marginalised over run intercept): (chain, draw)."""
    e = eta_arm(F, ai)                                   # C,S,I
    sc = F["sigma_c"][..., None, None]                   # C,S,1,1
    p = expit(e[..., None] + sc * GH_X)                  # C,S,I,K
    return (p * GH_W).sum(-1).sum(-1)


def predict_new_run(F, ai, rng, thin=1):
    e = eta_arm(F, ai)[:, ::thin]
    c = rng.normal(size=e.shape[:2]) * F["sigma_c"][:, ::thin]
    p = expit(e + c[..., None])
    return (rng.random(p.shape) < p).sum(-1)


def qci(x, lo=5, hi=95):
    return np.percentile(x, [lo, hi])


def flat(x):
    return np.asarray(x).reshape(-1)


# ----------------------------------------------------------------------------- reporting helpers
def fmt_ci(x, nd=2):
    a, b = qci(flat(x))
    return f"{flat(x).mean():.{nd}f} [{a:.{nd}f}, {b:.{nd}f}]"


def contrast_row(name, dA, cost_note=""):
    d = flat(dA)
    lo, hi = qci(d)
    return (f"| {name} | {d.mean():+.2f} | [{lo:+.2f}, {hi:+.2f}] | {np.mean(d > 0):.2f} | "
            f"{np.mean(d > 1):.2f} | {np.mean(np.abs(d) < 0.5):.2f} |{cost_note}")


def bootstrap_costs(costs, rng, nsamp):
    return {a: rng.choice(v, size=(nsamp, len(v)), replace=True).mean(1) for a, v in costs.items()}


